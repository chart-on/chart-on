/** A key of the shell's built-in text. */
export type ShellMessageKey = keyof typeof defaultShellMessages;

/** Anything that may carry a chart's language: a chart, or the options of a dialog opened for one. */
export type Localized = { readonly localization?: Localizer } | null | undefined;

const localizerOf = (source: Localized): Localizer => source?.localization ?? englishLocalizer;

/**
 * Text for an item that names a message key (a toolbar item's `labelKey`, say):
 * the key in the chart's language, `params` filled in, while `label` is still
 * the key's English default, else `label` as it is, so a label the app changed
 * wins. Keys without a built-in default (the app's own) always resolve, with
 * `label` as fallback.
 */
export function keyedText(chart: Localized, key: string | undefined, label: string, params?: MessageParams): string {
  if (key === undefined) return label;
  const english = (defaultShellMessages as Record<string, string>)[key] ?? (defaultMessages as Record<string, string>)[key];
  if (english !== undefined && englishLocalizer.text(key, params, english) !== label) return label;
  return localizerOf(chart).text(key, params, label);
}

/**
 * A built-in label whose key is made from an id (`appearance.<id>`, `category.<id>`, ...): the
 * key in the chart's language while `label` is still `english`, the built-in text, else `label`.
 */
export function builtinText(chart: Localized, key: string, label: string, english: string | undefined = label): string {
  return label === english ? localizerOf(chart).text(key, undefined, label) : label;
}

/** Internal: the message key `prefix` followed by `id` with a capital first letter, e.g. `railGroup` and `fib` give `railGroupFib`. */
export const keyOf = (prefix: string, id: string) => (prefix + id[0]!.toUpperCase() + id.slice(1)) as ShellMessageKey;

/** `key`'s built-in English text as `label`, and `key` as `labelKey`, for items that follow the chart's language. */
export const labelOf = <K extends ShellMessageKey>(labelKey: K) => ({ label: defaultShellMessages[labelKey], labelKey });

/** The shell text for `key` in the chart's language (its `localization` option), with `params` filled in. */
export function shellText(chart: Localized, key: ShellMessageKey, params?: MessageParams): string {
  return localizerOf(chart).text(key, params, defaultShellMessages[key]);
}

/** "No results", else the result count in the language's plural form, with a `+` while `more` may follow. */
export function resultsText(chart: Localized, count: number, more = false): string {
  if (count === 0) return shellText(chart, 'symbolSearchNoResults');
  const params = { count: `${count}${more ? '+' : ''}` };
  const fallback = shellText(chart, count === 1 && !more ? 'symbolSearchResult' : 'symbolSearchResults', params);
  return pluralText(localizerOf(chart), 'symbolSearchResults', count, params, fallback);
}
